#!/usr/bin/env bash
# PreToolUse(Edit|Write|MultiEdit): block edits to generated/secret paths, and to tests while a bugfix lock is held.
input=$(cat)
file=$(jq -r '.tool_input.file_path // empty' <<<"$input")
[ -z "$file" ] && exit 0
rel="${file#"$CLAUDE_PROJECT_DIR"/}"

case "$rel" in
  Xpeet.xcodeproj/*)
    echo "Blocked: $rel is generated by XcodeGen. Edit project.yml and run xcodegen generate." >&2; exit 2 ;;
  .env|.env.*|*.p8|*.p12|*.mobileprovision|*.cer|*/GoogleService-Info.plist|fastlane/.env*)
    echo "Blocked: $rel holds credentials. Ask the user to change it." >&2; exit 2 ;;
esac

# Test-first bugfix: once the failing test is committed, `touch .claude/bugfix.lock` and the test can't be bent to pass.
if [ -f "$CLAUDE_PROJECT_DIR/.claude/bugfix.lock" ] && [[ "$rel" == XpeetTests/* ]]; then
  echo "Blocked: bugfix.lock is set; fix the code, not the test ($rel). Remove .claude/bugfix.lock when done." >&2; exit 2
fi
exit 0
